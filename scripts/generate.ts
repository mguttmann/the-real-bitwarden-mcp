import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import type { OperationDef, ParameterDef } from "../src/types.js";

const HTTP_METHODS = ["get", "post", "put", "patch", "delete"] as const;
type Method = (typeof HTTP_METHODS)[number];

type SpecParam = {
  name: string;
  in: "path" | "query" | "header";
  required?: boolean;
  schema?: Record<string, unknown>;
  description?: string;
};
type SpecOperation = {
  summary?: string;
  description?: string;
  operationId?: string;
  parameters?: SpecParam[];
  requestBody?: {
    required?: boolean;
    content?: { "application/json"?: { schema?: Record<string, unknown> } };
  };
  responses?: Record<
    string,
    { content?: { "application/json"?: { schema?: Record<string, unknown> } } }
  >;
  tags?: string[];
};
type Spec = { paths: Record<string, Partial<Record<Method, SpecOperation>>> };

function isPathParam(s: string): boolean {
  return s.startsWith("{") && s.endsWith("}");
}
function singularize(p: string): string {
  if (p.endsWith("ies")) return p.slice(0, -3) + "y";
  if (p.endsWith("ses")) return p.slice(0, -2);
  if (p.endsWith("s") && !p.endsWith("ss")) return p.slice(0, -1);
  return p;
}

function normalizeSegment(s: string): string {
  return s.replace(/-/g, "_");
}

function chainAfterPublic(segs: string[]): string[] {
  const start = segs[0] === "public" ? 1 : 0;
  const chain: string[] = [];
  for (let i = start; i < segs.length; i++) {
    const s = segs[i]!;
    if (!isPathParam(s)) chain.push(normalizeSegment(s));
  }
  return chain;
}

export function deriveToolName(method: Method, path: string): string {
  const segs = path.split("/").filter(Boolean);
  const chain = chainAfterPublic(segs).map(singularize).join("_");
  const last = segs[segs.length - 1];
  const hasTailId = last !== undefined && isPathParam(last);
  const hasAnyPathParam = segs.some(isPathParam);

  let verb: string;
  if (method === "get") verb = hasTailId || hasAnyPathParam ? "get" : "list";
  else if (method === "delete") verb = "delete";
  else if (method === "put" || method === "patch") verb = "update";
  else verb = "create";
  return `bw_${chain}_${verb}_raw`;
}

function detectDestructive(method: Method): boolean {
  return method !== "get";
}

export function buildOperations(spec: Spec): OperationDef[] {
  const ops: OperationDef[] = [];
  for (const [path, methods] of Object.entries(spec.paths ?? {})) {
    if (!path.startsWith("/public")) continue;
    for (const m of HTTP_METHODS) {
      const op = methods?.[m];
      if (!op) continue;
      const toolName = deriveToolName(m, path);
      const parameters: ParameterDef[] = (op.parameters ?? []).map((p) => ({
        name: p.name,
        in: p.in,
        required: !!p.required,
        schema: p.schema ?? {},
        ...(p.description ? { description: p.description } : {}),
      }));
      const requestBodySchema = op.requestBody?.content?.["application/json"]?.schema;
      const requestBodyRequired = !!op.requestBody?.required;
      const okResponse = ["200", "201", "202", "204"]
        .map((s) => op.responses?.[s]?.content?.["application/json"]?.schema)
        .find(Boolean);
      ops.push({
        operationId: op.operationId ?? `${m}_${path}`.replace(/\W+/g, "_"),
        toolName,
        method: m.toUpperCase() as OperationDef["method"],
        path,
        summary: op.summary ?? "",
        description: op.description ?? "",
        tags: op.tags ?? [],
        parameters,
        ...(requestBodySchema ? { requestBodySchema } : {}),
        ...(requestBodySchema ? { requestBodyRequired } : {}),
        ...(okResponse ? { responseSchema: okResponse } : {}),
        isDestructive: detectDestructive(m),
      });
    }
  }
  ops.sort((a, b) => a.toolName.localeCompare(b.toolName));
  return ops;
}

function emit(operations: OperationDef[]): string {
  return (
    "// AUTO-GENERATED by scripts/generate.ts. Do not edit by hand.\n" +
    "// Run `npm run generate` after refreshing specs/public-api.spec.json.\n\n" +
    'import type { OperationDef } from "../../types.js";\n\n' +
    "export const OPERATIONS: OperationDef[] = " +
    JSON.stringify(operations, null, 2) +
    " as const;\n"
  );
}

async function main(): Promise<void> {
  const specPath = resolve(process.cwd(), "specs/public-api.spec.json");
  const outPath = resolve(process.cwd(), "src/tools/generated/operations.ts");
  const spec = JSON.parse(await readFile(specPath, "utf8")) as Spec;
  const operations = buildOperations(spec);
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, emit(operations), "utf8");
  process.stderr.write(`Wrote ${outPath} with ${operations.length} operations.\n`);
}

const isDirect =
  process.argv[1]?.endsWith("generate.ts") || process.argv[1]?.endsWith("generate.js");
if (isDirect) {
  main().catch((err) => {
    process.stderr.write(`generate failed: ${err instanceof Error ? err.message : err}\n`);
    process.exit(1);
  });
}
